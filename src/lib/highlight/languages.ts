const SHEBANGS: [RegExp, string][] = [
  [/\b(ba|z|k|da)?sh\b/, "shellscript"],
  [/\bfish\b/, "fish"],
  [/\bpython[\d.]*\b/, "python"],
  [/\bnode\b|\bdeno\b|\bbun\b/, "javascript"],
  [/\bruby\b/, "ruby"],
  [/\bperl\b/, "perl"],
  [/\bphp\b/, "php"],
  [/\blua\b/, "lua"],
  [/\bRscript\b/, "r"],
  [/\bosascript\b/, "applescript"],
];

/**
 * Returns a language id or alias that Shiki may know. The highlighter checks
 * that it is actually bundled and falls back to plain text.
 */
export function detectLanguage(path: string, firstLine?: string): string | null {
  const name = (path.split("/").pop() ?? path).toLowerCase();
  if (BY_NAME[name]) return BY_NAME[name];
  if (name.startsWith("dockerfile") || name.endsWith(".dockerfile")) return "docker";
  if (name.startsWith(".env.")) return "dotenv";
  if (name === "jenkinsfile") return "groovy";

  const dot = name.lastIndexOf(".");
  if (dot > 0 || (dot === 0 && name.length > 1)) {
    const ext = name.slice(dot + 1);
    return BY_EXT[ext] ?? ext;
  }

  if (firstLine?.startsWith("#!")) {
    for (const [re, lang] of SHEBANGS) if (re.test(firstLine)) return lang;
  }
  return null;
}
